enum AppLanguageSetting { system, zhHant, en }

extension AppLanguageSettingX on AppLanguageSetting {
  Locale? get locale {
    switch (this) {
      case AppLanguageSetting.system:
        return null;
      case AppLanguageSetting.zhHant:
        return const Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant');
      case AppLanguageSetting.en:
        return const Locale('en');
    }
  }

  String get label {
    switch (this) {
      case AppLanguageSetting.system:
        return tr('language.system.short');
      case AppLanguageSetting.zhHant:
        return tr('language.zhHant.short');
      case AppLanguageSetting.en:
        return tr('language.en.short');
    }
  }

  static AppLanguageSetting fromValue(String? value) {
    return AppLanguageSetting.values.firstWhere(
      (item) => item.name == value,
      orElse: () => AppLanguageSetting.system,
    );
  }
}

Locale _activeLocale = _normalizeAppLocale(currentPlatformLocale());

Locale _normalizeAppLocale(Locale locale) {
  final language = locale.languageCode.toLowerCase();
  if (language == 'en') return const Locale('en');
  return const Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant');
}

String _localeKey(Locale locale) {
  final normalized = _normalizeAppLocale(locale);
  if (normalized.languageCode == 'en') return 'en';
  final script = normalized.scriptCode?.toLowerCase();
  final country = normalized.countryCode?.toLowerCase();
  if (script == 'hant' ||
      country == 'tw' ||
      country == 'hk' ||
      country == 'mo' ||
      country == 'hant') {
    return 'zh_Hant';
  }
  return 'zh';
}

void setActiveLocale(Locale locale) {
  _activeLocale = _normalizeAppLocale(locale);
}

Locale resolveAppLocale(Locale? locale, Iterable<Locale> supportedLocales) {
  final source = locale ?? currentPlatformLocale();
  final resolved = _normalizeAppLocale(source);
  for (final supported in supportedLocales) {
    if (_localeKey(supported) == _localeKey(resolved)) {
      setActiveLocale(supported);
      return supported;
    }
  }
  const fallback = Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant');
  setActiveLocale(fallback);
  return fallback;
}

String tr(String key) {
  final localeKey = _localeKey(_activeLocale);
  if (localeKey == 'en') {
    return _en[key] ?? _enFull[key] ?? _englishFallbackForKey(key);
  }
  final simplified = _zhHans[key] ?? _zhHansFull[key] ?? _fallbackZhForKey(key);
  if (localeKey == 'zh_Hant') return _toTraditional(simplified);
  return simplified;
}

String tl(String text) {
  final localeKey = _localeKey(_activeLocale);
  if (localeKey == 'en') return _enLiteral[text] ?? text;
  if (localeKey == 'zh_Hant') return _toTraditional(text);
  return text;
}

String tlf(String text, Map<String, String> values) {
  var result = tl(text);
  for (final entry in values.entries) {
    result = result.replaceAll('{${entry.key}}', entry.value);
  }
  return result;
}

class AppLocalizations {
  final Locale locale;
  const AppLocalizations(this.locale);

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      AppLocalizations(_activeLocale);
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      locale.languageCode == 'zh' || locale.languageCode == 'en';

  @override
  Future<AppLocalizations> load(Locale locale) {
    final normalized = _normalizeAppLocale(locale);
    setActiveLocale(normalized);
    return SynchronousFuture(AppLocalizations(normalized));
  }

  @override
  bool shouldReload(covariant AppLocalizationsDelegate old) => false;
}

